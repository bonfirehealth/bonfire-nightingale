-- Parent/User Management
-- Stores primary user accounts and their platform state
CREATE TABLE parents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    
    -- Identity & Contact
    whatsapp_id VARCHAR(255) UNIQUE NOT NULL,    -- Primary identifier from WhatsApp
    full_name VARCHAR(255),
    phone_number VARCHAR(50),
    email VARCHAR(255) UNIQUE,
    postal_code VARCHAR(20),
    is_wtw_employee BOOLEAN NOT NULL DEFAULT FALSE,  -- Internal staff flag
    
    -- Platform State Management
    current_mode mode_enum NOT NULL DEFAULT 'awaiting_mode_selection',
    current_step VARCHAR(255),                    -- Current step in conversation flow
    
    -- Subscription Management
    subscription_status subscription_status_enum NOT NULL DEFAULT 'pre_trial',
    trial_start_date TIMESTAMPTZ,
    session_count INT NOT NULL DEFAULT 0,        -- Total coaching sessions count
    stripe_customer_id VARCHAR(255) UNIQUE,      -- Stripe customer reference
    
    -- Communication Management
    follow_up_sent_at TIMESTAMPTZ,               -- Last follow-up timestamp
    sent_trial_expiry BOOLEAN NOT NULL DEFAULT FALSE,  -- Trial expiry notification flag
    monthly_summary_sent_at TIMESTAMPTZ,         -- Last monthly report timestamp
    
    -- Audit Trail
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

