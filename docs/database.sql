-- Nudge Management: Determines if a user should receive promotional messages
CREATE OR REPLACE FUNCTION can_send_nudge_to_user(
    p_whatsapp_id VARCHAR(255),
    p_nudge_type VARCHAR(50)
) RETURNS BOOLEAN AS $$
DECLARE
    v_parent RECORD;
    v_days_since_trial_start INTEGER;
    v_session_count INTEGER;
    v_should_send BOOLEAN := FALSE;
BEGIN
    -- Retrieve parent details with trial duration
    SELECT 
        p.*,
        COALESCE(EXTRACT(DAY FROM (NOW() - p.trial_start_date)), 0)::INTEGER as trial_days
    INTO v_parent
    FROM parents p
    WHERE p.whatsapp_id = p_whatsapp_id;
    
    -- Validate parent exists and is in trial
    IF v_parent IS NULL OR v_parent.subscription_status != 'trialing' THEN
        RETURN FALSE;
    END IF;

    -- Count completed coaching sessions
    SELECT COUNT(*) INTO v_session_count 
    FROM coaching_sessions 
    WHERE parent_id = v_parent.id;

    -- Apply nudge-specific business rules
    CASE p_nudge_type
        WHEN 'trial_expiry' THEN
            -- Send trial expiry reminder after 7 days, once per trial
            IF v_parent.trial_days >= 7 
               AND NOT v_parent.sent_trial_expiry 
               AND v_parent.subscription_status = 'trialing' THEN
                v_should_send := TRUE;
            END IF;
            
        ELSE
            -- Unknown nudge type - default to no send
            v_should_send := FALSE;
    END CASE;
    
    RETURN v_should_send;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Monthly Reporting: Checks eligibility for monthly summary reports
CREATE OR REPLACE FUNCTION can_send_monthly_summary_to_user(
    p_whatsapp_id VARCHAR(255)
) RETURNS BOOLEAN AS $$
DECLARE
    v_parent_id BIGINT;
BEGIN
    -- Find parent by WhatsApp ID
    SELECT id INTO v_parent_id 
    FROM parents 
    WHERE whatsapp_id = p_whatsapp_id;
    
    IF v_parent_id IS NULL THEN
        RETURN FALSE;
    END IF;
    
    -- Check if user is eligible (trial or paid subscriber)
    IF EXISTS (
        SELECT 1
        FROM parents
        WHERE id = v_parent_id
          AND (subscription_status = 'trialing' OR subscription_status = 'active_paid')
    ) THEN
        RETURN TRUE;
    END IF;
    
    RETURN FALSE;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Monthly Report Generation: Creates summary statistics for user engagement
CREATE OR REPLACE FUNCTION create_monthly_summary_for_user(
    p_whatsapp_id VARCHAR(255)
) RETURNS TABLE (
    parent_full_name VARCHAR(255),
    successful_follow_ups INTEGER,
    total_sessions INTEGER
) AS $$
BEGIN
    RETURN QUERY
    WITH parent_info AS (
        SELECT id, full_name 
        FROM parents 
        WHERE whatsapp_id = p_whatsapp_id
    ),
    follow_ups AS (
        SELECT COUNT(*) as count
        FROM coaching_sessions
        WHERE parent_id = (SELECT id FROM parent_info)
          AND follow_up_outcome = 'succeeded'
          AND session_end_time >= (NOW() - INTERVAL '30 days')
    ),
    sessions AS (
        SELECT COUNT(*) as count
        FROM coaching_sessions
        WHERE parent_id = (SELECT id FROM parent_info)
          AND status = 'completed'
          AND session_end_time >= (NOW() - INTERVAL '30 days')
    )
    SELECT 
        p.full_name::VARCHAR(255),
        COALESCE(f.count, 0)::INTEGER,
        COALESCE(s.count, 0)::INTEGER
    FROM 
        parent_info p
        CROSS JOIN LATERAL (SELECT count FROM follow_ups) f
        CROSS JOIN LATERAL (SELECT count FROM sessions) s;
EXCEPTION
    WHEN OTHERS THEN
        -- Log error and return safe defaults
        RAISE NOTICE 'Error generating monthly report for %: %', p_whatsapp_id, SQLERRM;
        RETURN QUERY SELECT NULL::VARCHAR(255), NULL::INTEGER, NULL::INTEGER;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
